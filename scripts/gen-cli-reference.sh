# Regenerates docs/reference/CLI.md from the real --help output of target/debug/impulse and
# target/debug/impulse-watch (built with cargo build --locked). With --check, regenerates to a
# temporary file and fails if docs/reference/CLI.md differs.
set -euo pipefail
cd "$(dirname "$0")/.."

mode=write
case "${1:-}" in
  "") ;;
  --check) mode=check ;;
  *) echo "usage: scripts/gen-cli-reference.sh [--check]" >&2; exit 2 ;;
esac

cargo build --locked -q -p impulse-cli -p impulse-watch
bin=target/debug
out=$(mktemp); trap 'rm -f "$out"' EXIT

# Subcommand names from a --help text: the lines of its "Commands:" section, first word each,
# except "help".
subcommands() {
  awk '/^Commands:/{on=1; next} on && /^[^ ]/{on=0} on && /^  [a-z]/{print $1}' | grep -vx help || true
}

emit() { # emit <heading level> <command words...>; the title is the command as typed
  local level=$1; shift
  local title; title=$(basename "$1")
  [ $# -gt 1 ] && title="$(basename "$1") ${*:2}"
  local text
  text=$("$@" --help 2>&1) || { echo "gen-cli-reference: $* --help failed" >&2; exit 1; }
  printf '\n%s `%s`\n\n```text\n%s\n```\n' "$level" "$title" "$text" >>"$out"
  local sub
  for sub in $(subcommands <<<"$text"); do
    emit "${level}#" "$@" "$sub"
  done
}

cat >"$out" <<'HDR'
# Command-line reference

Generated by `scripts/gen-cli-reference.sh` from the `--help` output of `impulse` and `impulse-watch`. Do not edit by hand: `scripts/ci-local.sh` fails when this file is not what the script produces. For what each command does, in order and with the checks it makes, read [spec/CLI.md](../../spec/CLI.md); for the watcher, [spec/WATCH.md](../../spec/WATCH.md); for the IPST file format, [spec/IPST.md](../../spec/IPST.md). Error codes are indexed in [ERRORS.md](ERRORS.md).

Global rules that the help text does not repeat: mainnet is used only when `--network mainnet` is passed explicitly; a key is read only from a key file the user names on the command line, and never printed or logged; a trade above the value cap is refused (spec/CLI.md, "Value cap").

HDR
printf '## impulse\n' >>"$out"
emit '###' "$bin/impulse"
printf '\n## impulse-watch\n' >>"$out"
emit '###' "$bin/impulse-watch"

# Drop a trailing blank line difference and normalise: no trailing whitespace.
sed -i.bak -e 's/[[:space:]]*$//' "$out" && rm -f "$out.bak"

if [ "$mode" = check ]; then
  diff -u docs/reference/CLI.md "$out" >&2 || { echo "gen-cli-reference: docs/reference/CLI.md is stale; run scripts/gen-cli-reference.sh" >&2; exit 1; }
else
  cp "$out" docs/reference/CLI.md
fi
